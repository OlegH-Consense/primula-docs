"""Watermarks (specification 8.6, decision 84).

A text watermark is an SVG image generated by the translator: the text,
rotated by ``angle`` degrees counter-clockwise around the centre of the
text area, in ``color`` with ``opacity`` percent opacity.  Without
``size`` the font size is chosen so that the text takes about 80 % of the
diagonal of the text area (measured with the font metrics of
:mod:`primula.tables.metrics`).  An image watermark (``img(…)``) is used
as is.  The writer places either in a frame behind the text, anchored in
the header of every master page of the selected page styles.

Reference: SVG 1.1 ``text``, ``transform``, ``fill-opacity``,
https://www.w3.org/TR/SVG11/
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from fractions import Fraction
from typing import Any
from xml.sax.saxutils import escape, quoteattr

from primula.core.values import Length, parse_length
from primula.odf import units
from primula.pages.images import ImageInfo
from primula.tables.metrics import MM_PER_PT, FontKey, text_width


@dataclass(frozen=True)
class TextMark:
    """Parameters of a text watermark (decision 84)."""

    text: str
    angle: Fraction = Fraction(45)
    color: str = "#C8C8C8"
    size: Length | None = None
    opacity: int = 50
    font: str | None = None


def text_mark(mark: str, options: dict[str, Any]) -> TextMark:
    """A :class:`TextMark` from the options of ``watermark(…)``.

    Raises:
        ValueError: an invalid option (the name is the message).
    """
    angle = options.get("angle", 45)
    if isinstance(angle, bool) or not isinstance(angle, (int, float)) and type(angle).__name__ != "Decimal":
        raise ValueError("angle")
    color = options.get("color", "#C8C8C8")
    if not (isinstance(color, str) and len(color) == 7 and color.startswith("#")):
        raise ValueError("color")
    size = options.get("size")
    if size is not None and not isinstance(size, Length):
        size = parse_length(size) if isinstance(size, str) else None
        if size is None:
            raise ValueError("size")
    opacity = options.get("opacity", 50)
    if isinstance(opacity, bool) or not isinstance(opacity, int) or not 0 <= opacity <= 100:
        raise ValueError("opacity")
    font = options.get("font")
    if font is not None and not isinstance(font, str):
        raise ValueError("font")
    return TextMark(mark, Fraction(str(angle)), color, size, opacity, font)


def text_svg(mark: TextMark, area: tuple[Fraction, Fraction], default_font: str) -> bytes:
    """The SVG of a text watermark covering the text area (``area`` in millimetres).

    The SVG uses millimetres as user units, so its size is the text area.
    """
    width, height = area
    family = mark.font or default_font
    if mark.size is not None:
        size_pt = units.to_mm(mark.size) / MM_PER_PT
    else:
        # About 80 % of the diagonal (decision 84), but the rotated text must
        # also fit the area: LibreOffice does not clip an SVG to its viewBox.
        unit, _exact = text_width(mark.text, FontKey(family, bold=True), Fraction(1))
        diagonal = Fraction(math.hypot(float(width), float(height))).limit_denominator(1000)
        rad = math.radians(float(mark.angle))
        cos, sin = abs(math.cos(rad)), abs(math.sin(rad))
        line = float(MM_PER_PT) * 0.75  # glyph height per point (cap height ~0.72 em)
        limits = [float(diagonal) * 0.8 / float(unit)] if unit else [72.0]
        if unit:
            limits.append(0.9 * float(width) / (float(unit) * cos + line * sin))
            limits.append(0.9 * float(height) / (float(unit) * sin + line * cos))
        size_pt = Fraction(min(limits)).limit_denominator(100)
    size_mm = size_pt * MM_PER_PT
    cx, cy = width / 2, height / 2

    def num(value: Fraction) -> str:
        return f"{float(value):.3f}".rstrip("0").rstrip(".")

    text = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{num(width)}mm" height="{num(height)}mm" '
            f'viewBox="0 0 {num(width)} {num(height)}">'
            f'<text x="{num(cx)}" y="{num(cy)}" transform="rotate({num(-mark.angle)} {num(cx)} {num(cy)})" '
            f'text-anchor="middle" dominant-baseline="central" font-family={quoteattr(family)} '
            f'font-weight="bold" font-size="{num(size_mm)}" fill="{mark.color}" '
            f'fill-opacity="{num(Fraction(mark.opacity, 100))}">{escape(mark.text)}</text></svg>')
    return text.encode("utf-8")


@dataclass(frozen=True)
class Watermark:
    """A watermark of a page style: an image (generated SVG or a file) and its size."""

    image: ImageInfo
    width: Fraction
    height: Fraction
